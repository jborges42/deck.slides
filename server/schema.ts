// Tabelas do banco, no SQL comum ao SQLite (local e Turso) e ao Postgres (Supabase). Horários em milissegundos
// são BIGINT (no Postgres, INTEGER estoura). As chaves estrangeiras documentam as relações, mas as exclusões em
// cascata são feitas pelo código: o Turso (e cada conexão nova do libSQL) roda com foreign_keys desligado.
export type Dialect = 'sqlite' | 'postgres'

const TABLES = ['meta', 'moderators', 'events', 'participants', 'screens', 'scenes', 'questions', 'likes', 'reactions', 'media', 'signals', 'connections', 'pairings', 'hits']

export const schema = (dialect: Dialect) => `
  CREATE TABLE IF NOT EXISTS meta (key TEXT PRIMARY KEY, value TEXT NOT NULL);

  CREATE TABLE IF NOT EXISTS moderators (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE, -- sempre gravado em minúsculas
    password TEXT NOT NULL,
    session_epoch BIGINT NOT NULL DEFAULT 0, -- ms; sessões emitidas antes disto são inválidas
    created_at BIGINT NOT NULL
  );

  CREATE TABLE IF NOT EXISTS events (
    id TEXT PRIMARY KEY, -- código curto e legível (newCode), usado nas URLs
    name TEXT NOT NULL,
    pin TEXT NOT NULL,
    settings TEXT NOT NULL,
    theme TEXT NOT NULL,
    live TEXT NOT NULL,
    created_at BIGINT NOT NULL
  );

  CREATE TABLE IF NOT EXISTS participants (
    id TEXT PRIMARY KEY,
    event_id TEXT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    email TEXT NOT NULL DEFAULT '',
    grp TEXT NOT NULL DEFAULT '',
    token TEXT NOT NULL UNIQUE,
    source TEXT NOT NULL DEFAULT 'invite',
    blocked INTEGER NOT NULL DEFAULT 0,
    session_epoch BIGINT NOT NULL DEFAULT 0, -- ms; novo link de convite invalida sessões anteriores
    joined_at BIGINT,
    created_at BIGINT NOT NULL
  );
  CREATE INDEX IF NOT EXISTS participants_event ON participants(event_id);

  -- Telas pareadas por código: o segredo fica num cookie do computador da projeção; aqui, só o hash.
  CREATE TABLE IF NOT EXISTS screens (
    id TEXT PRIMARY KEY,
    event_id TEXT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    secret_hash TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    created_at BIGINT NOT NULL,
    last_seen BIGINT
  );
  CREATE INDEX IF NOT EXISTS screens_event ON screens(event_id);

  CREATE TABLE IF NOT EXISTS scenes (
    id TEXT PRIMARY KEY,
    event_id TEXT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    position INTEGER NOT NULL,
    type TEXT NOT NULL,
    name TEXT NOT NULL,
    content TEXT NOT NULL,
    created_at BIGINT NOT NULL
  );
  CREATE INDEX IF NOT EXISTS scenes_event ON scenes(event_id, position);

  CREATE TABLE IF NOT EXISTS questions (
    id TEXT PRIMARY KEY,
    event_id TEXT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    participant_id TEXT REFERENCES participants(id) ON DELETE SET NULL,
    author TEXT NOT NULL,
    anonymous INTEGER NOT NULL DEFAULT 0,
    original TEXT NOT NULL,
    text TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending',
    screen INTEGER,
    flagged INTEGER NOT NULL DEFAULT 0,
    created_at BIGINT NOT NULL
  );
  CREATE INDEX IF NOT EXISTS questions_event ON questions(event_id, created_at);
  CREATE INDEX IF NOT EXISTS questions_participant ON questions(participant_id);

  CREATE TABLE IF NOT EXISTS likes (
    question_id TEXT NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
    participant_id TEXT NOT NULL REFERENCES participants(id) ON DELETE CASCADE,
    PRIMARY KEY (question_id, participant_id)
  );
  CREATE INDEX IF NOT EXISTS likes_participant ON likes(participant_id);

  CREATE TABLE IF NOT EXISTS reactions (
    event_id TEXT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    scene_id TEXT NOT NULL,
    kind TEXT NOT NULL,
    count INTEGER NOT NULL,
    PRIMARY KEY (event_id, scene_id, kind)
  );

  CREATE TABLE IF NOT EXISTS media (
    id TEXT PRIMARY KEY,
    event_id TEXT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    kind TEXT NOT NULL,
    name TEXT NOT NULL,
    file TEXT NOT NULL,
    mime TEXT NOT NULL,
    size BIGINT NOT NULL,
    created_at BIGINT NOT NULL,
    blob_url TEXT -- endereço no Vercel Blob; nulo quando o arquivo está em DATA_DIR/uploads
  );
  CREATE INDEX IF NOT EXISTS media_event ON media(event_id);

  -- Estado compartilhado entre instâncias do servidor (na Vercel, várias rodam ao mesmo tempo).

  -- Avisos de mudança: cada instância lê os das outras e republica para as conexões que ela segura.
  CREATE TABLE IF NOT EXISTS signals (
    id ${dialect === 'postgres' ? 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY AUTOINCREMENT'},
    instance TEXT NOT NULL,
    event_id TEXT NOT NULL,
    targets TEXT NOT NULL, -- JSON: audiências ("moderator", "p:<id>", "counts", "kick:p:<id>"...)
    created_at BIGINT NOT NULL
  );

  -- Conexões SSE abertas (presença). "seen" é renovado pela instância dona; parado há muito tempo = offline.
  CREATE TABLE IF NOT EXISTS connections (
    id TEXT PRIMARY KEY,
    instance TEXT NOT NULL,
    event_id TEXT NOT NULL,
    audience TEXT NOT NULL,
    participant_id TEXT,
    screen_id TEXT,
    seen BIGINT NOT NULL
  );
  CREATE INDEX IF NOT EXISTS connections_event ON connections(event_id, seen);

  -- Códigos de pareamento de telas ainda não vinculadas (chave: hash do segredo do cookie da tela).
  CREATE TABLE IF NOT EXISTS pairings (
    secret_hash TEXT PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    expires BIGINT NOT NULL
  );

  -- Limites de tentativas: contagem por chave numa janela de tempo.
  CREATE TABLE IF NOT EXISTS hits (
    key TEXT PRIMARY KEY,
    n INTEGER NOT NULL,
    reset BIGINT NOT NULL
  );
${dialect === 'postgres' ? SUPABASE_LOCKDOWN : ''}`

// Supabase publica o schema public pela Data API (chave anon, que é pública por definição). O app fala direto com
// o Postgres como dono das tabelas, que ignora RLS: RLS ligado sem nenhuma política e sem privilégios para
// anon/authenticated fecha as tabelas para a Data API, mesmo com "expor tabelas novas" ligado no painel.
const SUPABASE_LOCKDOWN = `
  ${TABLES.map((t) => `ALTER TABLE ${t} ENABLE ROW LEVEL SECURITY;`).join('\n  ')}
  DO $$ BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
      REVOKE ALL ON ${TABLES.join(', ')} FROM anon, authenticated;
      REVOKE ALL ON SEQUENCE signals_id_seq FROM anon, authenticated;
    END IF;
  END $$;
`
